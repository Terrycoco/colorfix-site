if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
$pdo = new PDO('sqlite::memory:', null, null, [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
$pdo->sqliteCreateFunction('NOW', fn() => gmdate('Y-m-d H:i:s'));
$pdo->exec("CREATE TABLE articles (id INTEGER PRIMARY KEY, type TEXT, status TEXT DEFAULT 'draft', title TEXT, kicker TEXT, dek TEXT, slug TEXT, meta_description TEXT, hero_asset_id INTEGER, hero_inset_asset_id INTEGER, hero_inset_positions TEXT, hero_mobile_asset_id INTEGER, cta_overrides TEXT, featured INTEGER, published_at TEXT, created_at TEXT, updated_at TEXT);
