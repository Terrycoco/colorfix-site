$count = 0;
function check(bool $ok, string $message): void { global $count; if (!$ok) throw new RuntimeException($message); $count++; }
function rejects(callable $fn, string $message): void { try { $fn(); } catch (Throwable $e) { check(true, $message); return; } check(false, $message); }
$repo = new PdoArticleRepository($pdo);
$save = new ArticleService($repo);
$publication = new ArticlePublicationService($pdo);
$id = $save->saveArticle(['title'=>'Test <Artwork>', 'slug'=>'test', 'tags'=>null, 'status'=>'published', 'published_at'=>'2000-01-01']);
check($repo->getArticleById($id)['status'] === 'draft', 'Ordinary creation must remain draft');
check($repo->getArticleById($id)['published_at'] === null, 'Client timestamp ignored');
check((new PublicArticleService($pdo))->get($id, false)['status'] === 403, 'Anonymous draft denied');
check((new PublicArticleService($pdo))->get($id, true)['status'] === 200, 'Authenticated preview allowed');
$first = $publication->publish($id);
check($first['status'] === 'published' && !empty($first['published_at']), 'First publication');
check($publication->publish($id) === $first, 'Repeat publication stable');
check((new PublicArticleService($pdo))->get($id, false)['status'] === 200, 'Anonymous published access');
$save->saveArticle(['id'=>$id,'title'=>'Edited', 'slug'=>'test', 'tags'=>null, 'status'=>'draft','published_at'=>'2099-01-01']);
check($repo->getArticleById($id)['status'] === 'published', 'Ordinary edit cannot unpublish');
check($repo->getArticleById($id)['published_at'] === $first['published_at'], 'Ordinary edit preserves first date');
$unpublished = $publication->unpublish($id);
check($unpublished['published_at'] === $first['published_at'], 'Unpublish preserves date');
check($publication->unpublish($id) === $unpublished, 'Repeated unpublish stable');
check($publication->publish($id) === $first, 'Republish preserves original date');
rejects(fn() => $publication->publish(999), 'Missing article rejected');
check(!$pdo->inTransaction(), 'Failed own transaction rolled back');
$pdo->beginTransaction(); $publication->unpublish($id);
check($pdo->inTransaction(), 'Does not commit coordinator transaction'); $pdo->rollBack();
check($repo->getArticleById($id)['status'] === 'published', 'Coordinator rollback restores state');
$pdo->exec("INSERT INTO playlists (playlist_id,article_id,editorial_type) VALUES (71,1,'teaching'); INSERT INTO pub_assets VALUES (42,'article','playlist',71,'/articles/1',0,'created')");
$pub = new ArticlePublicationManager($pdo);
rejects(fn() => $pub->release(42,'publish'), 'PUB rejects unapproved asset');
$pdo->exec('UPDATE pub_assets SET approved=1');
check($pub->release(42,'publish') === $first, 'PUB reuses same publication');
$pub->release(42,'unpublish');
check($publication->publish($id) === $first, 'Editor can republish after PUB unpublish');
$pdo->exec("UPDATE pub_assets SET url='/articles/999'");
rejects(fn() => $pub->release(42,'publish'), 'Stale receipt rejected');
$pdo->exec("UPDATE pub_assets SET url='/articles/1', pipeline_stage='creating'");
rejects(fn() => $pub->release(42,'publish'), 'Incomplete article rejected');
$links = new ArticleLinkService($pdo);
$ctas = [['action_key'=>'article_link','params'=>json_encode(['article_id'=>$id])], ['action_key'=>'navigate','params'=>'{}']];
check(count($links->hydrate($ctas)) === 2, 'Published article CTA visible');
$publication->unpublish($id);
check(count($links->hydrate($ctas)) === 1, 'Draft article CTA removed');
check($links->hydrate([['action_key'=>'article_link','params'=>'{"url":"/articles/1"}']]) === [], 'Explicit draft article URL removed');
check($repo->getFeaturedOrLatest() === null, 'Draft excluded from featured selection');
$sitemap = new RexSitemapService($pdo);
check($sitemap->urls() === [RexSitemapService::ORIGIN . '/'], 'Stale ANA article paths excluded');
$publication->publish($id);
check(in_array(RexSitemapService::ORIGIN . '/articles/1', $sitemap->urls(), true), 'Published article in sitemap');
check((int)$repo->getFeaturedOrLatest()['id'] === $id, 'Published available to featured selection');
$listing = new \App\ARTICLES\Services\ArticleListingService($pdo);
check(array_column($listing->list(), 'id') === [$id], 'Public listing includes published articles');
$publication->unpublish($id);
check($listing->list() === [], 'Public listing excludes unpublished articles immediately');
check(count($save->listArticles([])) === 1, 'Admin listing retains draft');
$publication->publish($id);
$item = ['article'=>$repo->getArticleById($id), 'hero'=>['optimized_urls'=>['1600'=>'/api/v2/image-thumb.php?id=12&w=1600']]];
$item['article']['title'] = 'Test <Artwork> & "Colors"';
$item['article']['meta_description'] = 'A description';
$shell = '<!doctype html><head><title>Generic</title><meta name="robots" content="index,follow"><meta property="og:title" content="Generic"><link rel="canonical" href="https://wrong.test"></head><body><div id="root"></div></body>';
$html = ArticleHtmlService::render($shell, $item);
check(str_contains($html, 'Test &lt;Artwork&gt; &amp; &quot;Colors&quot;'), 'Metadata escaped');
check(!str_contains($html, 'Generic') && !str_contains($html,'wrong.test'), 'Generic metadata replaced');
check(substr_count($html, '<title>') === 1 && substr_count($html, 'rel="canonical"') === 1, 'No duplicate title or canonical');
check(str_contains($html,'https://colorfix.terrymarr.com/articles/1'), 'Canonical uses existing public URL');
check(str_contains($html,'property="og:image"') && str_contains($html,'name="twitter:image"'), 'Social image metadata');
check(str_contains($html,'name="description" content="A description"'), 'Description metadata');
check(str_contains($html,'name="robots" content="index,follow"'), 'Public indexability');
$private = ArticleHtmlService::render($shell, null);
check(str_contains($private,'noindex,nofollow') && !str_contains($private,'Generic'), 'Anonymous unavailable HTML not generic/indexable');
check(!str_contains($private, 'rel="canonical"') && !str_contains($private, 'Test &lt;'), 'Unavailable HTML exposes no article metadata');
check(str_contains(ArticleHtmlService::render($shell,$item,true),'noindex,nofollow'), 'Authenticated preview not indexed');
echo "PASS: $count publication, approval, privacy, metadata, discovery and transaction checks (SQLite only)\n";
